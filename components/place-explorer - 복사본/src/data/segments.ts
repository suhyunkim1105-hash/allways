/* =========================================================================
 * segments.ts
 * -------------------------------------------------------------------------
 * Accessibility route segments, sourced from the app's real measured-path
 * export (appdata.json → `segments`), which is more complete/authoritative
 * than the raw spreadsheet: it includes actual walked GPS coordinate
 * traces (not straight lines) for most segments, plus flagged hazard
 * points and route "gap" points (e.g. take an elevator here) along the
 * way.
 *
 * `measured` tells you which is which:
 *   - true  → `path` is the real multi-point walked route.
 *   - false → this segment hasn't been walked yet (`verdict: 'pending'`,
 *             appdata's 정보없음); `path` is just a straight 2-point line
 *             between the two endpoints as a placeholder until it's
 *             measured (all 6 unmeasured segments are on the Yongsan
 *             course: ST10→YS02→YS03→YS05→YS01, plus ST06→YS01 and
 *             YS05→YS06).
 *
 * `verdict` mirrors the source's per-segment verdict: 초록→'ok' (기본,
 * 파랑), 노랑→'caution' / 빨강→'danger' (둘 다 위험구간, 지도에선 같은 주황
 * — verdict 값 자체는 구분해서 보존하되 표시 색은 나누지 않음),
 * 정보없음→'pending' (측정 예정, 회색 점선).
 * =======================================================================*/

export type SegmentVerdict = 'ok' | 'caution' | 'danger' | 'pending';

